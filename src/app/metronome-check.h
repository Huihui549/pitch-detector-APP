// 节拍器离线自检（`--metrocheck` / `--metrowav`）
//
// 为什么要它：节拍器"准不准"无法靠肉眼看界面判断，而手机端既没有终端也没有 logcat 通道。
// 本自检**完全不碰声卡**，直接把 core 渲染器产出的样点拿来做数值断言：
//   · 每个点击落在哪个样点（与"由拍号/细分独立算出的期望位置"逐项比对，容差 1 个样点）
//   · 相同拍位在不同块长（512 / 4096）下渲染结果必须**逐位相同**（可复现性）
//   · 三种角色的发声次数与音色幅度关系（强拍 > 弱拍 > 细分）
//   · 自定义样本装载后，点击起始处应逐样点等于"素材 × 增益"
//   · 无削顶、无 NaN
// 另外 `--metrowav <路径>` 会把同一段渲染写成 WAV，供人耳试听（用户可在电脑上直接听）。
//
// 编码要求（坑 A20）：本文件必须存为 UTF-8 **无 BOM**。

#pragma once

#include <QString>

namespace pitch {

/// 运行节拍器离线自检。
/// @param wavOut 非空时，额外把 4 小节渲染结果写成 WAV（供人耳试听）
/// @return 0 = 全部通过；非 0 = 有断言失败（打印出的 [FAIL] 行即原因）
int runMetronomeCheck(const QString& wavOut);

} // namespace pitch
